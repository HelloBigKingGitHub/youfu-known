def test_section_metadata_includes_extractor(fixtures_dir: Path) -> None:
    """Every section carries ``metadata.extractor`` from a known set."""
    p = fixtures_dir / "sample_text.pdf"
    if not p.exists():
        pytest.skip(f"fixture missing: {p}")
    sections = parse_pdf_v2(p)
    valid_extractors = ("pymupdf", "pymupdf+pdfplumber", "pypdf_fallback")
    for s in sections:
        assert "metadata" in s
        assert "extractor" in s["metadata"]
        assert s["metadata"]["extractor"] in valid_extractors


