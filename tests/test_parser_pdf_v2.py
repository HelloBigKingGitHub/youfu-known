def test_load_document_dispatches_to_v2_for_pdf(fixtures_dir: Path) -> None:
    """``load_document`` uses parser_pdf_v2 by default for ``.pdf`` files.

    The result must be non-empty and carry the v2 metadata shape.
    """
    from app.rag.loader import load_document

    p = fixtures_dir / "sample_text.pdf"
    if not p.exists():
        pytest.skip(f"fixture missing: {p}")
    sections = load_document(p)  # prefer_v2=True is the default
    assert len(sections) >= 1
    # At least one section must be tagged with an extractor field.
    assert any("extractor" in s.get("metadata", {}) for s in sections)


def test_pymupdf_import_succeeded() -> None:
    """Smoke test: the PyMuPDF import succeeded at module load.

    If this ever fails it means the environment is missing the
    aarch64 wheel; the rest of the v2 path will fall back to pypdf
    gracefully (covered by the test above).
    """
