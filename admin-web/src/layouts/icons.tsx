// Type-cast chakra icons so they can be used as the `as` prop without
// importing the `react-icons` library. We re-export small inline SVG
// components so the bundle stays minimal and there are no extra deps.
import { type ComponentType, type SVGProps } from 'react'

type IconComponent = ComponentType<SVGProps<SVGSVGElement>>

function makeIcon(path: JSX.Element): IconComponent {
  const Icon = (props: SVGProps<SVGSVGElement>) => (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.6"
      strokeLinecap="round"
      strokeLinejoin="round"
      width="1em"
      height="1em"
      {...props}
    >
      {path}
    </svg>
  )
  return Icon
}

